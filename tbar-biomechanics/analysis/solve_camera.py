"""Recover the lever's true angle from the tracked hub.

Model: pinhole camera (zero roll) looking at a rigid lever that rotates in a
vertical plane about the calibrated pivot.
  lever direction  d(theta) = cos(theta) * H + sin(theta) * U
  U = world up, H = horizontal direction of the lever plane (towards plates)
Unknowns: focal length f, camera pitch, lever-plane yaw, pivot depth (in lever
lengths), and theta for every frame. Fitted to:
  * the tracked hub position in every 3rd frame (reprojection error)
  * the plate-face ellipses (plate face is perpendicular to the lever)
  * the floor-tile horizon (soft prior on pitch)
Then theta is re-solved for every frame and lightly smoothed.

Output: src/data/tracking.json (consumed by the Remotion composition).
"""
import json
import os

import numpy as np
from scipy.optimize import least_squares, minimize_scalar
from scipy.signal import find_peaks, savgol_filter

HERE = os.path.dirname(os.path.abspath(__file__))
cal = json.load(open(os.path.join(HERE, "calibration.json")))
hub = np.array(json.load(open(os.path.join(HERE, "out", "hub_track.json"))))[:, :2]
N = len(hub)
cx, cy = cal["sourceWidth"] / 2, cal["sourceHeight"] / 2
p0 = np.array(cal["pivot"], float)
ell = cal["plateEllipses"]
sub = np.arange(0, N, 3)


def basis(beta, psi):
    U = np.array([0, -np.cos(beta), np.sin(beta)])
    Fw = np.array([0, np.sin(beta), np.cos(beta)])
    X = np.array([1.0, 0, 0])
    H = -np.cos(psi) * X - np.sin(psi) * Fw
    return H, U


def proj(P, f):
    return np.stack([f * P[..., 0] / P[..., 2] + cx, f * P[..., 1] / P[..., 2] + cy], -1)


def model(g, th):
    f, beta, psi, Z0 = g
    P0 = Z0 * np.array([(p0[0] - cx) / f, (p0[1] - cy) / f, 1.0])
    H, U = basis(beta, psi)
    d = np.cos(th)[:, None] * H + np.sin(th)[:, None] * U
    return P0, d, P0 + d


def resid(p):
    g, th = p[:4], p[4:]
    f = g[0]
    _, _, C = model(g, th)
    r = [((proj(C, f) - hub[sub]) / 1.5).ravel()]
    the = np.interp([e[0] for e in ell], sub, th)
    _, de, Ce = model(g, the)
    for k, (_, ratio, ang) in enumerate(ell):
        ray = Ce[k] / np.linalg.norm(Ce[k])
        r.append([(abs(de[k] @ ray) - ratio) / 0.04])
        v = proj(Ce[k] + 0.05 * de[k], f) - proj(Ce[k], f)
        da = ((np.degrees(np.arctan2(v[1], v[0])) % 180 - ang + 90) % 180) - 90
        r.append([da / 4.0])
    r.append([(cy + f * np.tan(g[1]) - cal["horizonY"]) / 25.0])
    return np.concatenate(r)


best = None
for f0 in (450, 650, 850):
    for psi0 in (0.5, 0.8, 1.1):
        for z0 in (1.5, 2.5, 4.0):
            x0 = np.r_[[f0, 0.0, psi0, z0], np.full(len(sub), 0.3)]
            lb = np.r_[[200, -0.6, 0.05, 0.3], np.full(len(sub), -1.2)]
            ub = np.r_[[2000, 0.6, 1.5, 20], np.full(len(sub), 1.5)]
            s = least_squares(resid, x0, bounds=(lb, ub))
            if best is None or s.cost < best.cost:
                best = s
f, beta, psi, Z0 = best.x[:4]
g = (f, beta, psi, Z0)
r = resid(best.x)
rms = float(np.sqrt(np.mean((r[: 2 * len(sub)] * 1.5) ** 2)))
print("f=%.0fpx pitch=%.1fdeg yaw=%.1fdeg pivotDepth=%.2fL  hub rms=%.2fpx"
      % (f, np.degrees(beta), np.degrees(psi), Z0, rms))

# ---- per-frame theta -----------------------------------------------------
theta = np.empty(N)
prev = 0.3
for i in range(N):
    def err(t):
        _, _, C = model(g, np.array([t]))
        return float(np.sum((proj(C, f)[0] - hub[i]) ** 2))
    res = minimize_scalar(err, bounds=(prev - 0.4, prev + 0.4), method="bounded")
    theta[i] = prev = res.x
theta_s = savgol_filter(theta, 9, 3)
_, _, Cm = model(g, theta_s)
fit = proj(Cm, f)
offset = savgol_filter(hub - fit, 15, 2, axis=0)  # keep overlay locked to the real plate

deg = np.degrees(theta_s)
bottoms, _ = find_peaks(-deg, distance=60, prominence=8)
tops, _ = find_peaks(deg, distance=60, prominence=8)
print("theta range %.1f..%.1f deg" % (deg.min(), deg.max()))
print("bottoms", [(int(i), round(float(deg[i]), 1)) for i in bottoms])
print("tops   ", [(int(i), round(float(deg[i]), 1)) for i in tops])

out = {
    "_note": "Generated by analysis/solve_camera.py - do not edit by hand. Pixels are source pixels.",
    "fps": cal["fps"],
    "sourceWidth": cal["sourceWidth"],
    "sourceHeight": cal["sourceHeight"],
    "camera": {"f": f, "cx": cx, "cy": cy, "pitch": beta, "yaw": psi, "pivotDepth": Z0},
    "pivot": cal["pivot"],
    "plateStackFraction": cal["plateStackFraction"],
    "hubRmsPx": rms,
    "bottoms": [int(i) for i in bottoms],
    "tops": [int(i) for i in tops],
    "theta": [round(float(t), 5) for t in theta_s],
    "offset": [[round(float(a), 2), round(float(b), 2)] for a, b in offset],
    "hub": [[round(float(a), 2), round(float(b), 2)] for a, b in hub],
}
dst = os.path.join(HERE, "..", "src", "data", "tracking.json")
json.dump(out, open(dst, "w"))
print("wrote", os.path.normpath(dst))
