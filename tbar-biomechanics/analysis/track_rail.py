"""Track the plate carriage on the rail machine (copy_932A...mov).

The carriage only translates along the rail (no rotation), so a single fixed
template of the plate hub is enough. Also fits a straight line to the path to
check that the rail really is straight.

Output: src/data/rail.json (source pixels, one entry per frame).
"""
import json
import os

import cv2
import numpy as np
from scipy.signal import find_peaks, savgol_filter

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "..", "copy_932AC2E1-8BF7-48A5-A7BC-C7824A74D862.mov")
SEED_FRAME, SEED = 30, (355.0, 500.0)  # hand-picked plate-hub position (source px)
R, SEARCH = 22, 30

cap = cv2.VideoCapture(SRC)
G = []
while True:
    ok, f = cap.read()
    if not ok:
        break
    G.append(cv2.GaussianBlur(cv2.cvtColor(f, cv2.COLOR_BGR2GRAY), (3, 3), 0).astype(np.float32))
N = len(G)


def patch(g, x, y):
    xi, yi = int(round(x)), int(round(y))
    return g[yi - R : yi + R + 1, xi - R : xi + R + 1]


tpl = patch(G[SEED_FRAME], *SEED)
pos = np.zeros((N, 2))
score = np.zeros(N)
for order in (range(SEED_FRAME, N), range(SEED_FRAME, -1, -1)):
    x, y = SEED
    for i in order:
        xi, yi = int(round(x)), int(round(y))
        x0, y0 = xi - R - SEARCH, yi - R - SEARCH
        res = cv2.matchTemplate(G[i][y0 : yi + R + SEARCH + 1, x0 : xi + R + SEARCH + 1], tpl, cv2.TM_CCOEFF_NORMED)
        _, mv, _, (px, py) = cv2.minMaxLoc(res)
        x, y = x0 + px + R, y0 + py + R
        pos[i], score[i] = (x, y), mv

smooth = savgol_filter(pos, 9, 2, axis=0)
# straightness: principal direction of the path and perpendicular scatter
c = smooth.mean(0)
_, _, vt = np.linalg.svd(smooth - c)
d = vt[0] if vt[0][1] < 0 else -vt[0]  # unit direction pointing up the rail
along = (smooth - c) @ d
perp = (smooth - c) @ np.array([-d[1], d[0]])
print("frames", N, "match score min %.3f median %.3f" % (score.min(), np.median(score)))
print("travel along rail %.1f px, perpendicular scatter rms %.2f px (max %.2f)"
      % (along.max() - along.min(), perp.std(), np.abs(perp).max()))
print("rail direction in image: %.1f deg above horizontal" % np.degrees(np.arctan2(-d[1], abs(d[0]))))
tops, _ = find_peaks(along, distance=60, prominence=20)
bottoms, _ = find_peaks(-along, distance=60, prominence=20)
print("tops", tops.tolist(), "bottoms", bottoms.tolist())

out = {
    "_note": "Generated by analysis/track_rail.py. Source pixels.",
    "sourceWidth": 480,
    "sourceHeight": 854,
    "railDir": d.tolist(),
    "railCentre": c.tolist(),
    "alongMin": float(along.min()),
    "alongMax": float(along.max()),
    "tops": tops.tolist(),
    "bottoms": bottoms.tolist(),
    "plate": [[round(float(a), 2), round(float(b), 2)] for a, b in smooth],
}
json.dump(out, open(os.path.join(HERE, "..", "src", "data", "rail.json"), "w"))
